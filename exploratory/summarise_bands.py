"""Summary of the hard-case band sensitivity (POST HOC; second outside review, 2026-11-12).

Pools the day-queries of the unconfigured threshold sets (dissolved oxygen 4.5 and 5.5 mg/L; pH 6.3 and 6.7 below, 9.2 and 8.8
above; conductance change 5% and 20%; 7DADM 19 and 21 degC) as the confirmation's estimand does (every day-query and loss draw
counted), for the scored populations narrow, study, wide, near (study band without the event rule) and all day-queries.
The first four come from exploratory/out/<tag>_bands/, the last from exploratory/out/<tag>/ (explore4.py, subset "all").
Writes draft4/tables/explore_bands.tex (sealed cohort) and prints all three years. Run from Paper3/:
  python -I -W ignore exploratory/summarise_bands.py
"""
import glob
import os

import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
ALT = {"do": (4.5, 5.5), "ph_low": (6.3, 6.7), "ph_high": (9.2, 8.8), "ec": (0.05, 0.2), "win7": (19.0, 21.0)}
CONDS = [(6, "iid_0.3"), (6, "gil_0.3_b3"), (12, "iid_0.3"), (12, "gil_0.3_b3")]
POPS = [("narrow", "Narrow bands"), ("study", "Study bands"), ("wide", "Wide bands"), ("near", "Study bands, no event rule"),
        ("all", "All day-queries")]
TAGS = [("rehearsal4_2023", "2023 (development)"), ("rehearsal4v2", "2024, cohort 3 (development)"),
        ("confirm4", "2022, cohort 4 (confirmation)")]


def load(tag):
    parts = []
    fb = glob.glob(os.path.join(ROOT, "exploratory", "out", tag + "_bands", "*.csv"))
    if fb:
        parts.append(pd.concat(pd.read_csv(f, dtype={"site": str}) for f in fb))
    fa = glob.glob(os.path.join(ROOT, "exploratory", "out", tag, "*.csv"))
    a = pd.concat(pd.read_csv(f, dtype={"site": str}) for f in fa)
    parts.append(a[a.subset == "all"])
    d = pd.concat(parts)
    d["theta"] = pd.to_numeric(d.theta, errors="coerce").round(3)
    m = False
    for k, v in ALT.items():
        m = m | ((d.metric == k) & d.theta.isin(v))
    return d[m], len(fb), len(fa)


def contrasts(d):
    g = d.groupby(["subset", "Q", "cond", "design"])[["sum", "count", "wrong"]].sum()
    share = (g["sum"] / g["count"]).unstack("design")
    n = g["count"].unstack("design")["rec"]
    return share, n, int(g["wrong"].sum())


def main():
    out = {}
    for tag, label in TAGS:
        d, nb, na = load(tag)
        share, n, wrong = contrasts(d)
        out[tag] = (share, n)
        print(f"{label}: {nb} band files, {na} explore4 files, wrong certain decisions {wrong}")
        for pop, plabel in POPS:
            cells = []
            for q, c in CONDS:
                if (pop, q, c) not in share.index:
                    cells.append("n/a")
                    continue
                s = share.loc[(pop, q, c)]
                cells.append(f"{s.heur - s.flagsrec:+.3f}/{s.heur - s.rec:+.3f} (n={int(n.loc[(pop, q, c)])})")
            print(f"  {plabel:28s} " + "  ".join(cells))
    _, nb, na = load("confirm4")
    if nb != na:
        print(f"sealed cohort incomplete ({nb} of {na} sites); table not written")
        return
    share, n = out["confirm4"]
    lines = []
    for pop, plabel in POPS:
        cells = []
        for q, c in CONDS:
            s = share.loc[(pop, q, c)]
            cells.append(f"{s.heur - s.flagsrec:+.3f} ({s.heur - s.rec:+.3f})")
        share6 = int(n.loc[(pop, 6, "iid_0.3")]) // 20
        lines.append(f"{plabel} & {share6:,} & " + " & ".join(cells) + r" \\")
    path = os.path.join(ROOT, "draft4", "tables", "explore_bands.tex")
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write("% generated by exploratory/summarise_bands.py (post hoc); do not edit\n" + "\n".join(lines) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
