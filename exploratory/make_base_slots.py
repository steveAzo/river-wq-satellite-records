"""Create exploratory/base_slots.py from the frozen src/p3v3/proto_base4.py with one change: the tolerance x 0.5 and send-on-delta
designs use SLOTS value slots per message (4 on the CRC-24 frame) instead of the literal 5 of the CRC-16 frame. Outside review, point 5;
POST HOC. The frozen file is read, never written. Run from Paper3/: python -I exploratory/make_base_slots.py"""
src = open("src/p3v3/proto_base4.py", encoding="utf-8").read()
old_a = 'g, mode = [([("R", p) for p in range(len(vals))], 5)], "coded"'
old_b = 'g = [([("R", p) for p in range(len(vals))], 5)]'
assert src.count(old_a) == 1 and src.count(old_b) == 1, "unexpected source"
src = src.replace(old_a, old_a.replace(", 5)]", ", SLOTS)]")).replace(old_b, old_b.replace(", 5)]", ", SLOTS)]"))
src = src.replace("sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))",
                  "sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'p3v3'))")
src = src.replace('sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))',
                  'sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))')
header = ('"""GENERATED by exploratory/make_base_slots.py from src/p3v3/proto_base4.py (frozen): tolerance x 0.5 and send-on-delta use SLOTS\n'
          'slots per message. POST HOC, outside review point 5. Do not edit; regenerate."""\n')
open("exploratory/base_slots.py", "w", encoding="utf-8").write(header + src)
print("exploratory/base_slots.py written")
